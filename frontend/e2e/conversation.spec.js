import { expect, test } from '@playwright/test'

test('reported greeting is conversational and never displays source excerpts', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Continue without signing in/i }).click()
  await page.getByPlaceholder(/Ask an academic question/i).fill("hi'")
  const reply = page.waitForResponse(r => r.url().endsWith('/api/v1/chat') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Send query' }).click()
  const data = await (await reply).json()
  expect(data.grounding_status).toBe('conversational')
  expect(data.response_time_ms).toBeLessThan(1000)
  expect(data.citations).toEqual([])
  await expect(page.getByText('Hi! How can I help you with QAU today?')).toBeVisible()
  await expect(page.locator('.evidence-source')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'History', exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/conversation.png', fullPage: true })
})

test('semester fee comes from the archived table with an inspectable citation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Continue without signing in/i }).click()
  await page.getByPlaceholder(/Ask an academic question/i).fill('What is the BSCS morning semester fee for Fall 2025?')
  const reply = page.waitForResponse(r => r.url().endsWith('/api/v1/chat') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Send query' }).click()
  const data = await (await reply).json()
  expect(data.grounding_status).toBe('cited_lookup')
  expect(data.model_backend).toBe('retrieval')
  expect(data.response_time_ms).toBeLessThan(5000)
  await expect(page.getByText(/Regular: Rs 60,860 per semester/)).toBeVisible()
  await expect(page.getByText(/The archived Fall 2025 BSCS fee table/)).toBeVisible()
  await expect(page.locator('.evidence-source')).toHaveCount(1)
  await expect(page.locator('.evidence-source')).not.toHaveAttribute('open')
  await page.locator('.evidence-source summary').click()
  await expect(page.getByRole('link', { name: /Open official source/ })).toBeVisible()
})

test('a greeting followed by a research question returns the published directory', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Continue without signing in/i }).click()
  await page.getByPlaceholder(/Ask an academic question/i).fill('Hi, what are the research groups in the department?')
  const reply = page.waitForResponse(r => r.url().endsWith('/api/v1/chat') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Send query' }).click()
  const data = await (await reply).json()
  expect(data.grounding_status).toBe('cited_lookup')
  expect(data.response_time_ms).toBeLessThan(5000)
  const answer = page.locator('.message-row.assistant .message-bubble').last()
  await expect(answer).toContainText('Human Information Interaction')
  await expect(answer).toContainText('Knowledge Engineering')
  await expect(answer).toContainText('Networking and Communication')
})
